-- Profile photo support for every authenticated account (all seven portals use public.profiles).
-- Apply after 001 and 002 in a reviewed Supabase project.
alter table public.profiles add column if not exists avatar_url text;
alter table public.profiles add column if not exists display_name text;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('profile-photos', 'profile-photos', false, 3145728, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=false, file_size_limit=3145728, allowed_mime_types=array['image/jpeg','image/png','image/webp'];

-- Files are stored under the authenticated user's UUID folder: <auth.uid()>/profile.jpg
-- A user can upload/update/delete only their own photo. Signed URLs are generated by the UI after auth.
drop policy if exists "Users can read own profile photos" on storage.objects;
create policy "Users can read own profile photos" on storage.objects for select to authenticated
using (bucket_id='profile-photos' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users can upload own profile photos" on storage.objects;
create policy "Users can upload own profile photos" on storage.objects for insert to authenticated
with check (bucket_id='profile-photos' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users can update own profile photos" on storage.objects;
create policy "Users can update own profile photos" on storage.objects for update to authenticated
using (bucket_id='profile-photos' and (storage.foldername(name))[1] = auth.uid()::text)
with check (bucket_id='profile-photos' and (storage.foldername(name))[1] = auth.uid()::text);
drop policy if exists "Users can delete own profile photos" on storage.objects;
create policy "Users can delete own profile photos" on storage.objects for delete to authenticated
using (bucket_id='profile-photos' and (storage.foldername(name))[1] = auth.uid()::text);
